package com.example.ai.controller;

import com.example.ai.tools.AgentTools;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.ai.chat.client.advisor.SimpleLoggerAdvisor;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

/**
 * Controller demonstrating the AI Agent capabilities in Spring AI 1.0.0.
 *
 * Key Concepts:
 * 1. Autonomy: The LLM autonomously chooses which @Tool annotated method to execute based on user intent.
 * 2. Multi-step Execution: If a query requires both weather and allowance calculation,
 *    the LLM calls both tools sequentially and synthesizes the final response.
 * 3. Observability: SimpleLoggerAdvisor logs the raw model prompt and tool call payload to the console.
 */
@RestController
@RequestMapping("/ai/agent")
public class AgentController {

    private final ChatClient chatClient;
    private final AgentTools agentTools;

    public AgentController(ChatClient.Builder builder, AgentTools agentTools) {
        this.agentTools = agentTools;
        this.chatClient = builder
                .defaultSystem("""
                        你是一个专业、严谨的企业行政与出行助手。
                        你可以根据用户的需求，自主判断并使用手头的工具来查询信息或执行计算。
                        要求：
                        1. 如果用户的问题涉及天气或穿衣出行，调用对应天气工具查询；
                        2. 如果用户的问题涉及出差补贴金额，调用对应补贴计算工具；
                        3. 如果工具返回了数据，必须据实引用工具给出的数字和建议回答，不要捏造；
                        4. 如果用户只是进行日常问候或技术咨询，不需要调用任何工具，直接礼貌回答。
                        """)
                .defaultAdvisors(new SimpleLoggerAdvisor())
                .build();
    }

    /**
     * Agent execution endpoint.
     *
     * Example calls:
     * 1. Multi-tool call:
     *    GET /ai/agent/ask?prompt=我下周要到北京出差4天，那边天气冷不冷？我总共能领多少出差补贴？
     * 2. Single-tool call:
     *    GET /ai/agent/ask?prompt=上海现在的天气怎么样？
     * 3. No-tool call:
     *    GET /ai/agent/ask?prompt=你好，请介绍一下你自己。
     *
     * @param prompt User's question or instruction
     * @return Synthesized answer generated by LLM after autonomous tool invocation
     */
    @GetMapping("/ask")
    public String askAgent(@RequestParam String prompt) {
        System.out.println("\n==================== [Agent Request Start] ====================");
        System.out.println("User Prompt: " + prompt);

        String response = chatClient.prompt()
                .user(prompt)
                // Pass the AgentTools bean containing @Tool methods directly
                .tools(agentTools)
                .call()
                .content();

        System.out.println("Agent Response: " + response);
        System.out.println("==================== [Agent Request End] ====================\n");
        return response;
    }
}
